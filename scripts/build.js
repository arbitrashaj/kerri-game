const fs = require('node:fs');
const path = require('node:path');
const { Script } = require('node:vm');
const root=path.resolve(__dirname,'..'), web=path.join(root,'www');
const native=process.argv.includes('--native');
const serverUrl=(process.env.SERVER_URL||'').replace(/\/$/,'');
if(serverUrl) {
  const parsed=new URL(serverUrl);
  const local=['localhost','127.0.0.1','[::1]'].includes(parsed.hostname);
  if(parsed.username||parsed.password||parsed.search||parsed.hash||parsed.pathname!=='/' ||
    (parsed.protocol!=='https:'&&!(process.env.ALLOW_INSECURE_LOCALHOST==='true'&&local&&parsed.protocol==='http:'))) {
    throw Error('SERVER_URL must be an HTTPS origin. HTTP localhost requires ALLOW_INSECURE_LOCALHOST=true.');
  }
}
if(native&&!serverUrl) throw Error('Native build requires SERVER_URL pointing to the deployed HTTPS game server.');
const html=fs.readFileSync(path.join(web,'index.html'),'utf8');
for(const match of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)) new Script(match[1]);
for(const file of fs.readdirSync(web).filter(file=>file.endsWith('.js')&&file!=='config.js')) new Script(fs.readFileSync(path.join(web,file),'utf8'),{filename:file});
fs.mkdirSync(path.join(web,'vendor'),{recursive:true});
fs.copyFileSync(path.join(root,'node_modules/socket.io/client-dist/socket.io.min.js'),path.join(web,'vendor/socket.io.min.js'));
fs.copyFileSync(path.join(root,'node_modules/socket.io/LICENSE'),path.join(web,'vendor/socket.io.LICENSE'));
fs.writeFileSync(path.join(web,'config.js'),'// Generated by scripts/build.js. Contains public configuration only.\nwindow.KERRI_SERVER_URL = '+JSON.stringify(serverUrl)+';\n');
console.log(`Web assets validated and prepared (${native?'native':'web'}). Server: ${serverUrl||'same origin'}`);
